#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Embed a binary (pycdc) as a zlib-compressed C array.

    mkres.py <binary> <out.c> <symbol-prefix>

Produces the three symbols single_main.c expects: <prefix>_raw_len,
<prefix>_comp_len and <prefix>_image[].
"""
import sys
import zlib


def main():
    src, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    data = open(src, 'rb').read()
    comp = zlib.compress(data, 9)

    lines = ['/* generated by mkres.py from %s */' % src,
             'const unsigned long %s_raw_len = %dUL;' % (name, len(data)),
             'const unsigned long %s_comp_len = %dUL;' % (name, len(comp)),
             'const unsigned char %s_image[] = {' % name]
    row = []
    for b in comp:
        row.append(str(b))
        if len(row) == 16:
            lines.append(','.join(row) + ',')
            row = []
    if row:
        lines.append(','.join(row) + ',')
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')
    sys.stderr.write('%s: %d -> %d bytes embedded\n' % (name, len(data), len(comp)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
